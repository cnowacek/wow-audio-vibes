#!/usr/bin/env python3
"""Render Audio Vibes signal chirps (.ogg) and the Audio Vibes addon's Commands.lua from protocol.json.

    python generate.py                       # render everything
    python generate.py --base-hz 15000       # override band
    python generate.py --amplitude-dbfs -55  # override level
    python generate.py --plot                # also write spectrogram
    python generate.py --no-zones            # skip the 512 zone files (faster while tuning)
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
import soundfile as sf

from vibes_proto import (REPO_ROOT, ZONE, Decoded, ZonePart, amp_db, decode_all, frame_symbols,
                          goertzel_amp, load_protocol, render_frame, render_zone_frame, zone_frame_symbols)

ADDON_NAME = "AudioVibes"  # WoW addon folder name (also the Lua global prefix)
ADDON_DIR = REPO_ROOT / "addon" / ADDON_NAME
SOUNDS_DIR = ADDON_DIR / "sounds"
LUA_SOUNDS = f"Interface\\\\AddOns\\\\{ADDON_NAME}\\\\sounds\\\\"
MAX_LOSS_DB = 6.0


def write_ogg(path: Path, pcm: np.ndarray, fs: int) -> str:
    """Write Ogg Vorbis at max quality. Returns which encoder was used."""
    try:
        # libsndfile: Vorbis quality = 1 - compression_level, so 0.0 == quality 1.0 (q10).
        sf.write(str(path), pcm, fs, format="OGG", subtype="VORBIS", compression_level=0.0)
        return "libsndfile q=1.0"
    except TypeError:
        pass  # old soundfile without compression_level
    except Exception as e:  # noqa: BLE001
        print(f"  libsndfile Vorbis write failed ({e}); trying external encoders")
    with tempfile.TemporaryDirectory() as td:
        wav = Path(td) / "x.wav"
        sf.write(str(wav), pcm, fs, subtype="FLOAT")
        if shutil.which("oggenc"):
            subprocess.run(["oggenc", "-Q", "-q", "10", "-o", str(path), str(wav)], check=True)
            return "oggenc -q 10"
        if shutil.which("ffmpeg"):
            subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-c:a", "libvorbis",
                            "-q:a", "10", str(path)], check=True)
            return "ffmpeg libvorbis -q:a 10"
    raise SystemExit("No Vorbis encoder available (need libsndfile with Vorbis, oggenc or ffmpeg).")


def roundtrip_report(p, symbols: list[int], orig: np.ndarray, decoded_pcm: np.ndarray):
    """Per-symbol Vorbis loss (dB) and margin over the other data tones, at the known symbol centres."""
    fs = p.sample_rate
    win = p.decoder["windowSamples"]
    hann = 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(win) / win)
    pad, pre, g, s = (p.samples(p.padding_ms), p.samples(p.preamble_ms),
                      p.samples(p.guard_ms), p.samples(p.symbol_ms))
    losses, snrs = [], []
    for i, sym in enumerate(symbols):
        c = pad + pre + g + i * (g + s) + s // 2
        so, sd = orig[c - win // 2: c + win // 2], decoded_pcm[c - win // 2: c + win // 2]
        f = p.data_hz[sym]
        lo = amp_db(goertzel_amp(so, f, fs, hann))
        ld = amp_db(goertzel_amp(sd, f, fs, hann))
        others = [amp_db(goertzel_amp(sd, h, fs, hann)) for k, h in enumerate(p.data_hz) if k != sym]
        losses.append(lo - ld)
        snrs.append(ld - max(others))
    return losses, snrs


def emit_lua(p, files: dict[int, str], zones: bool):
    g = f"{ADDON_NAME}Commands"
    lines = [
        "-- GENERATED by generator/generate.py from protocol/protocol.json. DO NOT EDIT.",
        f"{g} = {g} or {{}}",
        f"{g}.protocolVersion = {p.raw['version']}",
        f"{g}.codes = {{",
    ]
    for name, code in sorted(p.commands.items(), key=lambda kv: kv[1]):
        lines.append(f'  {name} = {code},')
    lines += ["}", f"{g}.files = {{"]
    for code in sorted(files):
        lines.append(f'  [{code}] = "{files[code]}",')
    lines += ["}"]
    if zones:
        lines += [
            "-- Zone frames: a 16-bit zone id is sent as part 0 (high byte) then part 1 (low byte).",
            f'{g}.zoneFilePattern = "{LUA_SOUNDS}zone_%d_%02x.ogg"',
            f"{g}.zoneInstanceFlag = {p.instance_flag}",
        ]
    lines.append("")
    (ADDON_DIR / "Commands.lua").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_locations_lua():
    """protocol/zones.json → addon Locations.lua (names, types, default playlist names, 'New in Forever')."""
    import json
    z = json.loads((REPO_ROOT / "protocol" / "zones.json").read_text(encoding="utf-8"))
    vibes = z["vibes"]
    g = f"{ADDON_NAME}Locations"
    lines = [
        "-- GENERATED by generator/generate.py from protocol/zones.json. DO NOT EDIT.",
        "-- Default playlist names are the companion's vibe names: the companion resolves the actual",
        "-- Spotify playlist; WoW can't read playlist names, so the vibe name is what the bar shows.",
        f"{g} = {{",
    ]
    def names(vibe_key):
        v = vibes.get(vibe_key, {})
        locked = v.get("name", vibe_key)
        relaxed = v.get("relaxed", {}).get("name", locked)
        return f"{{ relaxed = {lua_str(relaxed)}, locked = {lua_str(locked)} }}"

    for key, d in z["zones"].items():
        lines.append(f"  [{lua_str(key)}] = {{ name = {lua_str(d['name'])}, type = {lua_str(d['type'])}, "
                     f"vibe = {lua_str(d['vibe'])}, default = {names(d['vibe'])}"
                     + (", isNew = true" if d.get("isNew") else "") + " },")
    lines += ["}", f"{g}Categories = {{"]
    for evt, vibe in z["categories"].items():
        lines.append(f"  [{lua_str(evt)}] = {names(vibe)},")
    lines += ["}", ""]
    (ADDON_DIR / "Locations.lua").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Locations.lua -> {ADDON_DIR / 'Locations.lua'} ({len(z['zones'])} locations)")


def plot(p, title: str, pcm: np.ndarray, out: Path):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("matplotlib not installed; skipping --plot")
        return
    fig, ax = plt.subplots(figsize=(10, 4))
    ax.specgram(pcm, NFFT=1024, Fs=p.sample_rate, noverlap=896, cmap="magma", vmin=-200)
    ax.set_ylim(p.reference_hz[0] - 1000, p.reference_hz[1] + 1000)
    ax.set_title(f"{title} @ {p.amplitude_dbfs} dBFS")
    ax.set_xlabel("s")
    ax.set_ylabel("Hz")
    fig.tight_layout()
    fig.savefig(out, dpi=110)
    print(f"spectrogram -> {out}")


def check_file(p, path: Path, pcm: np.ndarray, symbols: list[int], expect) -> tuple[list[float], list[float], str | None]:
    back, fs = sf.read(str(path), dtype="float64", always_2d=True)
    back = back.mean(axis=1)
    if fs != p.sample_rate:
        return [], [], f"sample rate {fs}"
    n = min(len(back), len(pcm))
    losses, snrs = roundtrip_report(p, symbols, pcm[:n].astype(np.float64), back[:n])
    events = decode_all(p, back)
    got = [e for e in events if isinstance(e, (Decoded, ZonePart))]
    problem = None
    if not (len(got) == 1 and expect(got[0])):
        problem = f"decoder got {got}"
    elif max(losses) > MAX_LOSS_DB:
        problem = f"tone loss {max(losses):.1f} dB"
    return losses, snrs, problem


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-hz", type=float, help="override data band base frequency")
    ap.add_argument("--amplitude-dbfs", type=float, help="override peak amplitude")
    ap.add_argument("--plot", action="store_true", help="write spectrogram(s) for one command and one zone frame")
    ap.add_argument("--plot-code", type=int, default=2)
    ap.add_argument("--no-zones", action="store_true", help="skip zone frame files")
    args = ap.parse_args(argv)

    p = load_protocol(base_hz=args.base_hz, amplitude_dbfs=args.amplitude_dbfs)
    if args.base_hz is not None or args.amplitude_dbfs is not None:
        print("NOTE: overrides are NOT written back to protocol.json. Update protocol.json too, "
              "or the companion will listen on the old band/level.")
    SOUNDS_DIR.mkdir(parents=True, exist_ok=True)
    reserved = set(p.raw["frame"]["reservedCodes"])
    files: dict[int, str] = {}
    failures = []
    worst_loss, worst_snr = -1e9, 1e9
    encoder = None
    print(f"band {p.data_hz[0]:.0f}-{p.data_hz[-1]:.0f} Hz, command preamble {p.preamble_hz}, "
          f"zone preamble {p.zone_preamble_hz}, amplitude {p.amplitude_dbfs} dBFS")

    # ---- command frames ----
    for code in range(64):
        if code in reserved:
            continue
        pcm = render_frame(p, code)
        name = f"cmd_{code:02d}.ogg"
        path = SOUNDS_DIR / name
        encoder = write_ogg(path, pcm, p.sample_rate)
        files[code] = f"{LUA_SOUNDS}{name}"
        losses, snrs, problem = check_file(p, path, pcm, frame_symbols(p, code),
                                           lambda e, c=code: isinstance(e, Decoded) and e.code == c)
        if losses:
            worst_loss, worst_snr = max(worst_loss, max(losses)), min(worst_snr, min(snrs))
        print(f"  {'ok ' if not problem else 'BAD'} {name} {p.code_to_name.get(code, ''):<20} loss "
              + " ".join(f"{x:+.1f}" for x in losses) + " dB  snr "
              + " ".join(f"{x:.0f}" for x in snrs) + " dB" + (f"  {problem}" if problem else ""))
        if problem:
            failures.append(f"{name}: {problem}")
        if args.plot and code == args.plot_code:
            plot(p, f"cmd_{code:02d} ({p.code_to_name.get(code)})", pcm, REPO_ROOT / "generator" / "spectrogram.png")

    # ---- zone frames: 2 parts x 256 bytes ----
    if not args.no_zones:
        zone_bad = 0
        for part in (0, 1):
            for byte in range(256):
                pcm = render_zone_frame(p, part, byte)
                name = f"zone_{part}_{byte:02x}.ogg"
                path = SOUNDS_DIR / name
                write_ogg(path, pcm, p.sample_rate)
                losses, snrs, problem = check_file(
                    p, path, pcm, zone_frame_symbols(p, part, byte),
                    lambda e, pt=part, b=byte: isinstance(e, ZonePart) and e.part == pt and e.byte == b)
                if losses:
                    worst_loss, worst_snr = max(worst_loss, max(losses)), min(worst_snr, min(snrs))
                if problem:
                    zone_bad += 1
                    failures.append(f"{name}: {problem}")
                    print(f"  BAD {name}: {problem}")
                if args.plot and part == 0 and byte == 0x05:
                    plot(p, "zone_0_05 (zone frame)", pcm, REPO_ROOT / "generator" / "spectrogram-zone.png")
        print(f"  zone frames: {512 - zone_bad}/512 ok")

    emit_lua(p, files, zones=not args.no_zones)
    emit_locations_lua()
    print(f"\nencoder: {encoder}; {len(files)} command files"
          + ("" if args.no_zones else " + 512 zone files") + f" -> {SOUNDS_DIR}")
    print(f"worst Vorbis tone loss {worst_loss:+.2f} dB, worst symbol SNR {worst_snr:.1f} dB")
    print(f"Commands.lua -> {ADDON_DIR / 'Commands.lua'}")
    if failures:
        print(f"\nROUND-TRIP FAILED ({len(failures)}):")
        for f in failures[:20]:
            print("  - " + f)
        print("\nSuggestion: Vorbis is dropping the band. Try a lower band and/or level, e.g.\n"
              "  python generate.py --base-hz 15000 --amplitude-dbfs -40\n"
              "and then put the same values in protocol/protocol.json.")
        return 1
    print("\nRound-trip OK. Remember: restart WoW fully (not /reload) to pick up new sound files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
